"""Generate the API reference for Knap.

`mojo doc` extracts docstrings into JSON and does not generate HTML. Its own
help says the format is subject to change. That rules out building a
documentation site against it: the cost would be a renderer, and the
foundation is declared unstable by the tool that produces it. The same
reasoning keeps a Python wheel unpublished.

So this renders Markdown into the repository instead, and that turns out to
be the better artefact for this project rather than a consolation prize.

  * It renders on the forge with no site to deploy or keep alive.
  * It is committed, so `scripts/check_generated.py` fails the build when it
    drifts from the code.
  * **A change to the public surface appears in a pull request diff.** For a
    version that claims a settled interface, that is worth more than a
    browsable page. Adding a method, or quietly widening one, becomes
    something a reviewer sees rather than something they would have to go
    looking for.

Underscore prefixed names are omitted. The document is a statement about what
a consumer may rely on, and internals in it would be an invitation to rely on
those too.

    python scripts/gen_api_reference.py
    python scripts/gen_api_reference.py --check
"""

